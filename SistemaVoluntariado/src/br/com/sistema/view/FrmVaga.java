    private void carregarTabela() {
        try {

            List<Vaga> vagas = dao.listar();

            DefaultTableModel modelo = (DefaultTableModel) tabelaVagas.getModel();

            modelo.setRowCount(0);

            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");

            for (Vaga vaga : vagas) {

                modelo.addRow(new Object[]{
                    vaga.getId(),
                    vaga.getTitulo(),
                    vaga.getDescricao(),
                    vaga.getCargahoras(),
                    vaga.getNumerovagas(),
                    formato.format(vaga.getDatavaga()),
                    vaga.getStatus(),
                    vaga.getIdOrganizacao()
                });
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar vagas:\n"
                    + e.getMessage());
        }

    }

    private void limparCampos() {

        idSelecionado = 0;

        txtTitulo.setText("");
        txtDescricao.setText("");
        txtCargaHoras.setText("");
        txtNumeroVagas.setText("");
        txtData.setText("");
        cmbStatus.setText("");

        if (cmbOrganizacao.getItemCount() > 0) {
            cmbOrganizacao.setSelectedIndex(0);
        }

        tabelaVagas.clearSelection();

    }

    private void carregarOrganizacoes() {
        try {

            List<Organizacao> organizacoes = organizacaoDAO.listar();

            cmbOrganizacao.removeAllItems();

            for (Organizacao organizacao : organizacoes) {

                cmbOrganizacao.addItem(organizacao.getNome());

            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar organizações:\n"
                    + e.getMessage());
        }

    }

    private void selecionarOrganizacao(int idOrganizacao) {
        try {

            List<Organizacao> organizacoes = organizacaoDAO.listar();

            for (Organizacao organizacao : organizacoes) {

                if (organizacao.getId() == idOrganizacao) {

                    cmbOrganizacao.setSelectedItem(organizacao.getNome());

                    return;
                }
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao selecionar organização:\n"
                    + e.getMessage());
        }

    }

    private int buscarIdOrganizacao(String nomeOrganizacao) {

        try {

            List<Organizacao> organizacoes = organizacaoDAO.listar();

            for (Organizacao organizacao : organizacoes) {

                if (organizacao.getNome().equals(nomeOrganizacao)) {

                    return organizacao.getId();

                }
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao buscar organização:\n"
                    + e.getMessage());
        }

        return 0;
    }

