    private void tabelaVagasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaVagasMouseClicked
        int linha = tabelaVagas.getSelectedRow();

        if (linha >= 0) {

            idSelecionado = Integer.parseInt(
                    tabelaVagas.getValueAt(linha, 0).toString()
            );

            txtTitulo.setText(
                    tabelaVagas.getValueAt(linha, 1).toString()
            );

            txtDescricao.setText(
                    tabelaVagas.getValueAt(linha, 2).toString()
            );

            txtCargaHoras.setText(
                    tabelaVagas.getValueAt(linha, 3).toString()
            );

            txtNumeroVagas.setText(
                    tabelaVagas.getValueAt(linha, 4).toString()
            );

            txtData.setText(
                    tabelaVagas.getValueAt(linha, 5).toString()
            );

            cmbStatus.setText(
                    tabelaVagas.getValueAt(linha, 6).toString()
            );

            int idOrganizacao = Integer.parseInt(tabelaVagas.getValueAt(linha, 7).toString());

            selecionarOrganizacao(idOrganizacao);
        }
    }//GEN-LAST:event_tabelaVagasMouseClicked

