    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {

            String titulo = txtTitulo.getText().trim();
            String descricao = txtDescricao.getText().trim();
            String cargaH = txtCargaHoras.getText().trim();
            String numeroVagas = txtNumeroVagas.getText().trim();
            String data = txtData.getText().trim();
            String status = cmbStatus.getText().trim();

            String nomeOrganizacao
                    = (String) cmbOrganizacao.getSelectedItem();

            // Validação
            if (titulo.isEmpty()
                    || descricao.isEmpty()
                    || cargaH.isEmpty()
                    || numeroVagas.isEmpty()
                    || data.isEmpty()
                    || status.isEmpty()
                    || nomeOrganizacao == null
                    || nomeOrganizacao.trim().isEmpty()) {

                JOptionPane.showMessageDialog(this,
                        "Preencha todos os campos!");

                return;
            }

            int cargaHoras = Integer.parseInt(cargaH);
            int numeroVaga = Integer.parseInt(numeroVagas);

            // Busca o ID da organização pelo nome selecionado
            int idOrganizacao = buscarIdOrganizacao(nomeOrganizacao);

            if (idOrganizacao == 0) {

                JOptionPane.showMessageDialog(this,
                        "Organização não encontrada!");

                return;
            }

            // Converte a data
            SimpleDateFormat formato = new SimpleDateFormat("dd/MM/yyyy");
            formato.setLenient(false);
            java.util.Date dataVaga = formato.parse(data);

            // Cria a vaga
            Vaga vaga = new Vaga();

            vaga.setTitulo(titulo);
            vaga.setDescricao(descricao);
            vaga.setCargahoras(cargaHoras);
            vaga.setNumerovagas(numeroVaga);
            vaga.setDatavaga(dataVaga);
            vaga.setStatus(status);
            vaga.setIdOrganizacao(idOrganizacao);

            // Salva
            dao.salvar(vaga);

            JOptionPane.showMessageDialog(this,
                    "Vaga cadastrada com sucesso!");

            carregarTabela();
            limparCampos();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Carga horária e número de vagas devem ser números!");

        } catch (ParseException e) {

            JOptionPane.showMessageDialog(this,
                    "Data inválida! Digite no formato dd/MM/yyyy.");

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao salvar vaga:\n"
                    + e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

