    private void carregarTabela() {

        try {

            List<Voluntario> voluntarios = dao.listar();
            /* JOptionPane.showMessageDialog(this,
        "Quantidade de voluntários encontrados: " + voluntarios.size());
             */
            DefaultTableModel modelo
                    = (DefaultTableModel) tabelaVoluntarios.getModel();

            modelo.setRowCount(0);

            for (Voluntario voluntario : voluntarios) {

                modelo.addRow(new Object[]{
                    voluntario.getId(),
                    voluntario.getNome(),
                    voluntario.getEmail(),
                    voluntario.getTelefone(),
                    voluntario.getCidade(),
                    voluntario.getEstado(),
                    voluntario.getEndereco()
                });
            }

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao carregar voluntários: " + e.getMessage());
        }
    }

