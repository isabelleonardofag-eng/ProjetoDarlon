    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

        //faz a verificacao das informacoes
        if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um nome!");
            txtNome.requestFocus();
            return;
        }

        if (txtEmail.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um e-mail!");
            txtEmail.requestFocus();
            return;
        }

        if (txtTelefone.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um telefone!");
            txtTelefone.requestFocus();
            return;
        }

        if (txtCidade.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira uma cidade!");
            txtCidade.requestFocus();
            return;
        }

        //se tudo for bem verificado, cria-se novo voluntario com as infos passadas
        Voluntario voluntario = new Voluntario();

        voluntario.setNome(txtNome.getText().trim());
        voluntario.setEmail(txtEmail.getText().trim());
        voluntario.setTelefone(txtTelefone.getText().trim());
        voluntario.setCidade(txtCidade.getText().trim());
        voluntario.setEstado(txtEstado.getText().trim());
        voluntario.setEndereco(txtEndereco.getText().trim());

        try {

            dao.salvar(voluntario);

            JOptionPane.showMessageDialog(this,
                    "Voluntário cadastrado com sucesso!");

            carregarTabela();
            limparCampos();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao salvar voluntário: " + e.getMessage());
        }

    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um voluntário na tabela!");
            return;
        }

        if (txtNome.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um nome!");
            txtNome.requestFocus();
            return;
        }

        if (txtEmail.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um e-mail!");
            txtEmail.requestFocus();
            return;
        }

        if (txtTelefone.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira um telefone!");
            txtTelefone.requestFocus();
            return;
        }

        if (txtCidade.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Insira uma cidade!");
            txtCidade.requestFocus();
            return;
        }

        Voluntario voluntario = new Voluntario();

        voluntario.setId(idSelecionado);
        voluntario.setNome(txtNome.getText().trim());
        voluntario.setEmail(txtEmail.getText().trim());
        voluntario.setTelefone(txtTelefone.getText().trim());
        voluntario.setCidade(txtCidade.getText().trim());
        voluntario.setEstado(txtEstado.getText().trim());
        voluntario.setEndereco(txtEndereco.getText().trim());

        try {

            dao.editar(voluntario);

            JOptionPane.showMessageDialog(this,
                    "Voluntário atualizado com sucesso!");

            limparCampos();
            idSelecionado = 0;
            carregarTabela();

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(this,
                    "Erro ao editar voluntário: " + e.getMessage());
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void tabelaVoluntariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaVoluntariosMouseClicked
        int linha = tabelaVoluntarios.getSelectedRow();

        if (linha >= 0) {

            // Pega o ID da primeira coluna
            idSelecionado = Integer.parseInt(
                    tabelaVoluntarios.getValueAt(linha, 0).toString()
            );

            txtNome.setText(
                    tabelaVoluntarios.getValueAt(linha, 1).toString()
            );

            txtEmail.setText(
                    tabelaVoluntarios.getValueAt(linha, 2).toString()
            );

            txtTelefone.setText(
                    tabelaVoluntarios.getValueAt(linha, 3).toString()
            );

            txtCidade.setText(
                    tabelaVoluntarios.getValueAt(linha, 4).toString()
            );

            txtEstado.setText(
                    tabelaVoluntarios.getValueAt(linha, 5).toString()
            );

            txtEndereco.setText(
                    tabelaVoluntarios.getValueAt(linha, 6).toString()
            );
        }

    }//GEN-LAST:event_tabelaVoluntariosMouseClicked

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idSelecionado == 0) {
            JOptionPane.showMessageDialog(this,
                    "Selecione um voluntário na tabela!");
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir este voluntário?",
                "Confirmar exclusão",
                JOptionPane.YES_NO_OPTION
        );

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            dao.excluir(idSelecionado);

            JOptionPane.showMessageDialog(this,
                    "Voluntário excluído com sucesso!");

            limparCampos();
            carregarTabela();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                    "Erro ao excluir voluntário: " + e.getMessage());
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

